package main

import "fmt"

func main() {
	var arr [5]int
	fmt.Println(arr)
}

//here  we have declared an array of type int with a size of 5. Since we haven't assigned any values to the array, it will be initialized with the default value of 0 for each element. Therefore, when we print the array, it will output: [0 0 0 0 0].
